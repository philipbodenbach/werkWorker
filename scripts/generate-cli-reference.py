#!/usr/bin/env python3
"""Generate or check the public CLI reference from the release binary."""
import argparse
from pathlib import Path
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('binary', type=Path)
parser.add_argument('--check', action='store_true')
parser.add_argument('--output-dir', type=Path, default=Path('docs'))
args = parser.parse_args()
chunks = ['# CLI reference\n\nGenerated by `scripts/generate-cli-reference.py`. `ww` exposes the same commands.\n']
for command in [[], ['run'], ['tui'], ['resume'], ['sessions'], ['skills'], ['profiles'], ['sandbox'], ['rpc']]:
    help_text = subprocess.check_output([str(args.binary.resolve()), *command, '--help'], text=True)
    chunks.append('\n## ' + (' '.join(command) or 'werk-worker') + '\n\n```text\n' + help_text + '```\n')
content = ''.join(chunks)
path = args.output_dir / 'cli.md'
if args.check:
    if not path.exists() or path.read_text() != content:
        raise SystemExit('CLI reference is stale; regenerate docs/cli.md')
else:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
